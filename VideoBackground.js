const isAutoMatchedVideoInfo = (videoInfo) => {
    // A local edit explicitly makes zero a real first-lyric anchor, even if
    // the original automatic recommendation retained its system submitter.
    return videoInfo?.isAutoGenerated === true ||
        (videoInfo?.isAutoGenerated !== false && videoInfo?.submitterId === "system");
};

const getLyricsStartTimeSeconds = (firstLyricTime) => {
    if (firstLyricTime === null || firstLyricTime === undefined) {
        return null;
    }

    const parsedFirstLyricTime = Number(firstLyricTime);
    return Number.isFinite(parsedFirstLyricTime)
        ? parsedFirstLyricTime / 1000
        : null;
};

const getVideoSyncOffsetSeconds = (captionStartTime, lyricsStartTime, videoInfo) => {
    if (captionStartTime === null || captionStartTime === undefined) {
        return 0;
    }

    const parsedCaptionStartTime = Number(captionStartTime);
    if (!Number.isFinite(parsedCaptionStartTime)) {
        return 0;
    }

    if (lyricsStartTime === null || lyricsStartTime === undefined) {
        return 0;
    }

    const parsedLyricsStartTime = Number(lyricsStartTime);
    if (!Number.isFinite(parsedLyricsStartTime)) {
        return 0;
    }

    // System matches often use 0 as an unknown caption start. Treat that as song-start sync.
    if (isAutoMatchedVideoInfo(videoInfo) && Math.abs(parsedCaptionStartTime) < 0.001) {
        return 0;
    }

    return parsedCaptionStartTime - parsedLyricsStartTime;
};

