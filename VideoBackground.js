const isAutoMatchedVideoInfo = (videoInfo) => {
    return videoInfo?.isAutoGenerated === true || videoInfo?.submitterId === "system";
};

const getLyricsStartTimeSeconds = (firstLyricTime) => {
    if (firstLyricTime === null || firstLyricTime === undefined) {
        return null;
    }

    const parsedFirstLyricTime = Number(firstLyricTime);
    return Number.isFinite(parsedFirstLyricTime)
        ? parsedFirstLyricTime / 1000
        : null;
};

const getVideoSyncOffsetSeconds = (captionStartTime, lyricsStartTime, videoInfo) => {
    if (captionStartTime === null || captionStartTime === undefined) {
        return 0;
    }

    const parsedCaptionStartTime = Number(captionStartTime);
    if (!Number.isFinite(parsedCaptionStartTime)) {
        return 0;
    }

    if (lyricsStartTime === null || lyricsStartTime === undefined) {
        return 0;
    }

    const parsedLyricsStartTime = Number(lyricsStartTime);
    if (!Number.isFinite(parsedLyricsStartTime)) {
        return 0;
    }

    // System matches often use 0 as an unknown caption start. Treat that as song-start sync.
    if (isAutoMatchedVideoInfo(videoInfo) && Math.abs(parsedCaptionStartTime) < 0.001) {
        return 0;
    }

    return parsedCaptionStartTime - parsedLyricsStartTime;
};

const VIDEO_SYNC_INTERVAL_MS = 250;
const VIDEO_SYNC_SEEK_THRESHOLD_SECONDS = 0.5;

const resolveVideoSyncState = ({
    spotifyTime,
    lyricsStartTime,
    videoInfo,
    additionalDelaySeconds = 0,
    mapVideoTime,
}) => {
    const parsedSpotifyTime = Number(spotifyTime);
    const safeSpotifyTime = Number.isFinite(parsedSpotifyTime) ? parsedSpotifyTime : 0;
    const parsedAdditionalDelay = Number(additionalDelaySeconds);
    const safeAdditionalDelay = Number.isFinite(parsedAdditionalDelay) ? parsedAdditionalDelay : 0;
    const captionStartTime = videoInfo?.captionStartTime;
    const offset = getVideoSyncOffsetSeconds(captionStartTime, lyricsStartTime, videoInfo);
    const baseVideoTime = safeSpotifyTime + offset + safeAdditionalDelay;

    // The video has no timeline before 0. Keep its first frame still until the
    // Spotify position reaches the point that maps to the beginning of the video.
    if (baseVideoTime < 0) {
        return {
            baseVideoTime,
            targetVideoTime: 0,
            shouldHoldAtStart: true,
        };
    }

    const mappedVideoTime = typeof mapVideoTime === "function"
        ? Number(mapVideoTime(baseVideoTime, videoInfo?.skipSegments, captionStartTime))
        : baseVideoTime;

    return {
        baseVideoTime,
        targetVideoTime: Number.isFinite(mappedVideoTime) ? Math.max(0, mappedVideoTime) : 0,
        shouldHoldAtStart: false,
    };
};

const wrapVideoSyncTime = (targetVideoTime, duration) => {
    const parsedTarget = Number(targetVideoTime);
    const safeTarget = Number.isFinite(parsedTarget) ? Math.max(0, parsedTarget) : 0;
    const parsedDuration = Number(duration);
    if (Number.isFinite(parsedDuration) && parsedDuration > 0 && safeTarget >= parsedDuration) {
        return safeTarget % parsedDuration;
    }
    return safeTarget;
};

const syncYouTubePlayerTimeline = ({
    player,
    targetVideoTime,
    shouldHoldAtStart,
    shouldPlay,
    holdState,
}) => {
    if (!player || !holdState) return;

    const wasHoldingAtStart = holdState.isHolding === true;
    holdState.isHolding = shouldHoldAtStart === true;

    const playerState = player.getPlayerState();
    if (shouldHoldAtStart) {
        const currentVideoTime = player.getCurrentTime();
        const isAtStart = Number.isFinite(currentVideoTime) &&
            Math.abs(currentVideoTime) <= VIDEO_SYNC_SEEK_THRESHOLD_SECONDS;
        if (!wasHoldingAtStart || (!holdState.primePending && !isAtStart)) {
            // A paused YouTube iframe can keep painting its previous decoded frame
            // after seekTo(0). Let it reach PLAYING once so the frame is refreshed;
            // onStateChange pauses it again as soon as that frame is available.
            holdState.primePending = true;
            player.seekTo(0, true);
            player.playVideo();
            return;
        }

        if (holdState.primePending) {
            // Buffering can outlast a sync tick. Pausing here would cancel the
            // refresh and leave the previous frame visible for the whole intro.
            if (!settleYouTubeHoldPrime({ player, playerState, holdState }) &&
                playerState !== 1 && playerState !== 3) {
                if (!isAtStart) player.seekTo(0, true);
                player.playVideo();
            }
            return;
        }

        if (playerState === 1 || playerState === 3) {
            player.pauseVideo();
        }
        return;
    }

    holdState.primePending = false;
    const currentVideoTime = player.getCurrentTime();
    if (
        wasHoldingAtStart ||
        !Number.isFinite(currentVideoTime) ||
        Math.abs(currentVideoTime - targetVideoTime) > VIDEO_SYNC_SEEK_THRESHOLD_SECONDS
    ) {
        player.seekTo(targetVideoTime, true);
    }

    if (!shouldPlay) {
        if (playerState === 1 || playerState === 3) {
            player.pauseVideo();
        }
    } else if (playerState !== 1 && playerState !== 3) {
        player.playVideo();
    }
};

const settleYouTubeHoldPrime = ({ player, playerState, holdState }) => {
    if (
        !player ||
        playerState !== 1 ||
        holdState?.primePending !== true ||
        holdState?.isHolding !== true
    ) {
        return false;
    }

    // PLAYING may be queued from before seekTo(0). Wait until the player also
    // reports the start position, rather than freezing that stale frame again.
    const currentVideoTime = player.getCurrentTime();
    if (!Number.isFinite(currentVideoTime) ||
        Math.abs(currentVideoTime) > VIDEO_SYNC_SEEK_THRESHOLD_SECONDS) {
        return false;
    }

    holdState.primePending = false;
    player.pauseVideo();
    return true;
};

const disableYouTubeCaptions = (player) => {
    if (!player) return;

    try {
        if (typeof player.unloadModule === "function") {
            player.unloadModule("captions");
            player.unloadModule("cc");
        }
    } catch (e) { }

    try {
        if (typeof player.setOption === "function") {
            player.setOption("captions", "track", {});
            player.setOption("cc", "track", {});
        }
    } catch (e) { }
};

const isSpotifyPlaybackActive = (playerState = Spicetify.Player?.data) => {
    try {
        const isPaused = playerState?.is_paused ?? playerState?.isPaused;
        if (typeof isPaused === "boolean") {
            return !isPaused;
        }

        const isPlaying = playerState?.is_playing ?? playerState?.isPlaying;
        if (typeof isPlaying === "boolean") {
            return isPlaying;
        }

        return Boolean(Spicetify.Player?.isPlaying?.());
    } catch (e) {
        return false;
    }
};

