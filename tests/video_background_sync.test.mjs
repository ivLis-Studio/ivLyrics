    assert.equal(settleYouTubeHoldPrime({ player, playerState, holdState }), true);
    sync();
    assert.deepEqual(calls, [["seekTo", 0, true], ["playVideo"], ["pauseVideo"]]);
    assert.deepEqual(holdState, { isHolding: true, primePending: false });
