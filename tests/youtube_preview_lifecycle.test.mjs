import { VIDEO_SYNC_SEEK_THRESHOLD_SECONDS } from "../src/features/video/videoDriftCorrection.mjs";
import { preloadYouTubeIframeApi, watchYouTubeIframeApi } from "../src/features/video/youTubeIframeApi.mjs";

const previewSource = readCommunityVideoPreviewSource();
const wizardSource = readFileSync(new URL("../src/app/setupWizardVideoSteps.mjs", import.meta.url), "utf8");
const effectBody = (source, marker, ending) => {
  const markerIndex = source.indexOf(marker);
  const start = source.indexOf("useEffect(() => {", markerIndex);
  const end = source.indexOf(ending, start);
  assert.ok(markerIndex >= 0 && start > markerIndex && end > start);
  return source.slice(start + "useEffect(() => {".length, end);
};
const startWatch = previewSource.indexOf("const watchSync =");
const endWatch = previewSource.indexOf("// 헬퍼 모드: video 요소 설정", startWatch);
assert.ok(startWatch >= 0 && endWatch > startWatch);
const watchSyncSource = previewSource.slice(startWatch, endWatch);
const effects = {
  synced: effectBody(previewSource, "// 일반 모드: YouTube IFrame", "  }, [useHelper, videoId, trackUri, startTime, skipSegments, isAutoGenerated]);"),
  simple: effectBody(previewSource, "// 일반 모드: YouTube\n", "  }, [useHelper, videoId]);"),
  wizard: effectBody(wizardSource, "// Initialize YouTube Player API", "  }, []);"),
};

const createEnvironment = ({ yt, readyCallback, hidden = false } = {}) => {
  let nextId = 0;
  const timeouts = new Map();
  const intervals = new Map();
  const players = [];
  let frame = null;
  const songPlayer = new EventTarget();
  const scripts = new Set();
  const failedSources = [];
  const readyStates = [];
  const window = { YT: yt, onYouTubeIframeAPIReady: readyCallback, location: { origin: "https://example.test" } };
  const document = Object.assign(new EventTarget(), {
    hidden,
    head: { appendChild: script => scripts.add(script) },
    querySelectorAll: () => [...scripts],
    createElement: () => Object.assign(new EventTarget(), { style: {}, remove() { scripts.delete(this); } }),
    getElementById: () => null,
  });
  const schedule = (callback, delay) => { const id = ++nextId; timeouts.set(id, { callback, delay }); return id; };
  const cancel = id => timeouts.delete(id);
  return {
    window, timeouts, intervals, players, scripts, failedSources, readyStates, songPlayer,
    setFrame: next => { frame = next; },
    setHidden(hidden) {
      document.hidden = hidden;
      document.dispatchEvent(new Event("visibilitychange"));
    },
    preload: () => preloadYouTubeIframeApi(window, document),
    mount(name) {
      const node = { innerHTML: "", appendChild() {} };
      const source = "fixture";
      const context = vm.createContext({
        window, document, console: { ...console, warn() {}, error() {} },
        useHelper: false, videoId: "test-video", startTime: 0, skipSegments: [], isAutoGenerated: false, source,
        containerRef: { current: node }, playerContainerRef: { current: node },
        playerRef: { current: null }, playerIdRef: { current: "wizard-player" },
        setIsReady() {}, setPlayerReady: value => readyStates.push(value),
        setFailedSource: value => failedSources.push(value), writeRuntimeDebug() {}, startTimeRef: { current: 12.5 },
        Spicetify: { Player: songPlayer }, player: songPlayer, readPreviewFrame: () => frame, VIDEO_SYNC_SEEK_THRESHOLD_SECONDS,
        watchYouTubeIframeApi: options => watchYouTubeIframeApi({ ...options, schedule, cancel }),
        setTimeout: schedule, clearTimeout: cancel,
        setInterval(callback, delay) { const id = ++nextId; intervals.set(id, { callback, delay }); return id; },
        clearInterval: (id) => intervals.delete(id),
      });
      return vm.runInContext(`(() => { ${watchSyncSource} ${effects[name]} })()`, context);
    },
    loadApi() {
      window.YT = { Player: function Player(id, options) {
        this.id = id;
        this.options = options;
        this.destroyed = false;
        this.seeks = [];
        this.state = 1;
        this.time = 0;
        this.getCurrentTime = () => this.time;
        this.getPlayerState = () => this.state;
        this.seekTo = time => { this.seeks.push(time); this.time = time; };
        this.playVideo = () => { this.state = 1; };
        this.pauseVideo = () => { this.state = 2; };
        this.destroy = () => { this.destroyed = true; };
        players.push(this);
      } };
    },
    tick() {
      const [id, timer] = [...timeouts].sort((a, b) => a[1].delay - b[1].delay)[0];
      timeouts.delete(id);
      timer.callback();
    },
  };
};

for (const name of ["synced", "simple", "wizard"]) {
  test(`${name} cancels unavailable-API retry when closed and ignores an already queued callback`, () => {
    const environment = createEnvironment({ yt: {} });
    const cleanup = environment.mount(name);
    assert.equal(environment.timeouts.size, 2);
    const timer = [...environment.timeouts.values()].find(value => value.delay === 100);
    cleanup();
    assert.equal(environment.timeouts.size, 0);
    assert.equal(environment.intervals.size, 0);
    timer.callback();
    assert.equal(environment.timeouts.size, 0);
    environment.loadApi();
    timer.callback();
    assert.equal(environment.players.length, 0);
  });

  test(`${name} still initializes after delayed API loading while mounted and destroys its player`, () => {
    const environment = createEnvironment({ yt: {} });
    const cleanup = environment.mount(name);
    environment.tick();
    assert.equal(environment.timeouts.size, 2);
    environment.loadApi();
    environment.tick();
    assert.equal(environment.players.length, 1);
    assert.equal(environment.players[0].options.videoId, name === "wizard" ? "9bZkp7q19f0" : "test-video");
    assert.equal(environment.timeouts.size, 0);
    cleanup();
    assert.equal(environment.players[0].destroyed, true);
  });
}

test("closing a synced preview also cancels the initial playback sync queued by onReady", () => {
  const environment = createEnvironment();
  environment.loadApi();
  const cleanup = environment.mount("synced");
  environment.players[0].options.events.onReady();
  assert.equal(environment.timeouts.size, 1);
  assert.equal([...environment.timeouts.values()][0].delay, 500);
  cleanup();
  assert.equal(environment.timeouts.size, 0);
});

test("a synced preview avoids repeated seeks and pauses during a track handoff", () => {
  const environment = createEnvironment();
  environment.loadApi();
  const cleanup = environment.mount("synced");
  const preview = environment.players[0];
  const heartbeat = [...environment.intervals.values()][0].callback;
  environment.setFrame({ time: 10, playing: true });
  heartbeat();
  environment.setFrame({ time: 10.4, playing: true });
  heartbeat();
  assert.deepEqual(preview.seeks, [10]);
  environment.songPlayer.dispatchEvent(new Event("onseek"));
  assert.deepEqual(preview.seeks, [10, 10.4]);
  environment.setFrame(null);
  environment.songPlayer.dispatchEvent(new Event("songchange"));
  assert.equal(preview.state, 2);
  assert.deepEqual(preview.seeks, [10, 10.4]);
  environment.setFrame({ time: 2, playing: false });
  environment.songPlayer.dispatchEvent(new Event("songchange"));
  assert.equal(preview.state, 2);
  assert.deepEqual(preview.seeks, [10, 10.4, 2]);
  cleanup();
  heartbeat();
  environment.songPlayer.dispatchEvent(new Event("onseek"));
  assert.deepEqual(preview.seeks, [10, 10.4, 2]);
});

test("a simple preview that loads late seeks to the latest edited start time", () => {
  const environment = createEnvironment();
  environment.loadApi();
  const cleanup = environment.mount("simple");
  const player = environment.players[0];
  player.options.events.onReady();
  assert.deepEqual(player.seeks, [12.5]);
  cleanup();
});

test("wizard loads the player without taking ownership of the existing API-ready callback", () => {
  const calls = [];
  function previous(...args) { calls.push({ receiver: this, args }); }
  const environment = createEnvironment({ readyCallback: previous });
  const cleanup = environment.mount("wizard");
  assert.strictEqual(environment.window.onYouTubeIframeAPIReady, previous);
  environment.loadApi();
  environment.window.onYouTubeIframeAPIReady("ready");
  environment.tick();
  assert.equal(calls.length, 1);
  assert.strictEqual(calls[0].receiver, environment.window);
  assert.deepEqual(calls[0].args, ["ready"]);
  assert.equal(environment.players.length, 1);
  cleanup();
  assert.strictEqual(environment.window.onYouTubeIframeAPIReady, previous);
});

test("wizard cleanup retains a newer API callback and prevents late player creation", () => {
  const environment = createEnvironment();
  const cleanup = environment.mount("wizard");
  const newerCallback = () => {};
  environment.window.onYouTubeIframeAPIReady = newerCallback;
  cleanup();
  assert.strictEqual(environment.window.onYouTubeIframeAPIReady, newerCallback);
  environment.loadApi();
  newerCallback();
  assert.equal(environment.players.length, 0);
  assert.equal(environment.timeouts.size, 0);
});

test("background preload and three preview consumers share one script and one readiness wait", () => {
  const environment = createEnvironment({ yt: {} });
  const script = environment.preload();
  const stopWizard = environment.mount("wizard");
  const stopSynced = environment.mount("synced");
  const stopSimple = environment.mount("simple");
  assert.deepEqual([...environment.scripts], [script]);
  assert.equal(environment.timeouts.size, 2);
  stopSimple();
  assert.equal(environment.timeouts.size, 2);
  environment.loadApi();
  environment.tick();
  assert.deepEqual(environment.players.map(player => player.options.videoId), ["9bZkp7q19f0", "test-video"]);
  assert.equal(environment.timeouts.size, 0);
  stopSynced();
  stopWizard();
  assert.equal(environment.intervals.size, 0);
  assert.ok(environment.players.every(player => player.destroyed));
  environment.players[0].options.events.onReady();
  assert.deepEqual(environment.readyStates, [false], "a disposed wizard ignores the iframe's late onReady");
});

test("a failed script releases all waiters and a new preview can retry", () => {
  const environment = createEnvironment();
  const stopSynced = environment.mount("synced");
  const stopWizard = environment.mount("wizard");
  const [script] = environment.scripts;
  script.dispatchEvent(new Event("error"));
  assert.equal(environment.scripts.size, 0);
  assert.equal(environment.timeouts.size, 0);
  assert.equal(environment.failedSources.at(-1), "fixture");
  stopSynced();
  stopWizard();
  const stopRetry = environment.mount("simple");
  assert.equal(environment.scripts.size, 1);
  assert.notEqual([...environment.scripts][0], script);
  environment.loadApi();
  environment.tick();
  assert.equal(environment.players.length, 1);
  stopRetry();
});

test("an API timeout cleans up the script and ignores an already queued poll", () => {
  const environment = createEnvironment();
  const cleanup = environment.mount("synced");
  const [poll, deadline] = [...environment.timeouts.values()].sort((a, b) => a.delay - b.delay);
  deadline.callback();
  assert.equal(environment.timeouts.size, 0);
  assert.equal(environment.scripts.size, 0);
  assert.equal(environment.failedSources.at(-1), "fixture");
  environment.loadApi();
  poll.callback();
  assert.equal(environment.players.length, 0);
  cleanup();
});

test("the YouTube API watcher does not poll or expire while Spotify is hidden", () => {
  const environment = createEnvironment({ hidden: true });
  const stop = environment.mount("synced");
  assert.equal(environment.scripts.size, 1);
  assert.equal(environment.timeouts.size, 0);
  environment.loadApi();
  environment.setHidden(false);
  assert.equal(environment.players.length, 1);
  assert.equal(environment.timeouts.size, 0);
  stop();
  environment.setHidden(true);
  environment.setHidden(false);
  assert.equal(environment.players.length, 1);
});
