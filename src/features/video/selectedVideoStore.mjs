import { createRuntimeDebugLogger } from "#ivlyrics/spicetify/runtimeDebug.mjs";
import { awaitIdbRequest, openIdbDatabase, putIdbRecord, runIdbTransaction } from "../../core/indexedDbTransaction.mjs";
import { readSettingsDatabaseRecovery } from "../../core/settingsRuntime.mjs";

export const SELECTED_VIDEO_DATABASE = Object.freeze({ name: "ivLyricsSelectedVideos", storeName: "selectedVideos" });
const STORE_NAME = SELECTED_VIDEO_DATABASE.storeName;
const RETENTION_MS = 365 * 24 * 60 * 60 * 1000;

function cleanOldSelections(db) {
  const oldest = Date.now() - RETENTION_MS;
  const request = db.transaction(STORE_NAME, "readwrite").objectStore(STORE_NAME).openCursor();
  request.onsuccess = (event) => {
    const cursor = event.target.result;
    if (!cursor) return;
    if (cursor.value.savedAt && cursor.value.savedAt < oldest) cursor.delete();
    cursor.continue();
  };
}

export function openSelectedVideoDatabase(indexedDB) {
  return openIdbDatabase(indexedDB, SELECTED_VIDEO_DATABASE.name, 1, db => {
    if (!db.objectStoreNames.contains(STORE_NAME)) {
      db.createObjectStore(STORE_NAME, { keyPath: "trackUri" });
    }
  });
}

function putSelectedVideo(store, trackUri, videoInfo) {
  // The original backup manager could create this v1 store with external keys.
  return putIdbRecord(store, trackUri, { ...videoInfo, trackUri, savedAt: Date.now() });
}

export function createSelectedVideoStore({ getIndexedDb, waitForDatabaseRecovery, logDebug = () => {} }) {
  async function withDatabase(operation) {
    if (waitForDatabaseRecovery) await waitForDatabaseRecovery();
    const db = await openSelectedVideoDatabase(getIndexedDb());
    try {
      return await operation(db);
    } finally {
      db.close();
    }
  }

  function mutateSelection(trackUri, update) {
    return withDatabase(db => runIdbTransaction(db, STORE_NAME, "readwrite", tx => new Promise((resolve, reject) => {
      const store = tx.objectStore(STORE_NAME);
      const request = store.get(trackUri);
      request.onsuccess = () => {
        try {
          const next = update(request.result);
          if (next === undefined) return resolve(false);
          if (next === null) store.delete(trackUri);
          else putSelectedVideo(store, trackUri, next);
          resolve(true);
        } catch (error) {
          reject(error);
        }
      };
      request.onerror = () => reject(request.error);
    }), "Video selection transaction failed"));
  }

  return {
    async saveSelectedVideo(trackUri, videoInfo) {
      try {
        await withDatabase(async (db) => {
          await runIdbTransaction(db, STORE_NAME, "readwrite", tx => {
            putSelectedVideo(tx.objectStore(STORE_NAME), trackUri, videoInfo);
          }, "Video selection transaction failed");
          try {
            cleanOldSelections(db);
          } catch {
            // A cleanup failure should not invalidate a committed selection.
          }
        });
        logDebug(`[ivLyrics] Saved selected video for ${trackUri}:`, videoInfo.youtubeVideoId);
        return true;
      } catch (error) {
        console.error("[ivLyrics] Failed to save selected video:", error);
        return false;
      }
    },

    // Keep the comparison and write in one transaction. A queued offset
    // adjustment for an old video must not overwrite a replacement.
    updateSelectedVideoSyncOffset(trackUri, videoInfo) {
      if (!trackUri || !videoInfo?.youtubeVideoId || !Number.isFinite(videoInfo.captionStartTime)) return Promise.resolve(false);
      return mutateSelection(trackUri, (existing) => {
        if (existing && existing.youtubeVideoId !== videoInfo.youtubeVideoId) return;
        return {
          ...videoInfo,
          ...existing,
          captionStartTime: videoInfo.captionStartTime,
          isAutoGenerated: false,
        };
      });
    },

    replaceHiddenSelectedVideo(trackUri, previous, replacement, isCurrent) {
      return mutateSelection(trackUri, (existing) => {
        // A user may have picked a different video or edited its timing while
        // the community lookup was underway.
        if (!isCurrent() || !existing ||
            existing.youtubeVideoId !== previous.youtubeVideoId ||
            existing.communityEntryId !== previous.communityEntryId ||
            existing.savedAt !== previous.savedAt ||
            existing.captionStartTime !== previous.captionStartTime) return;
        return replacement;
      });
    },

    async getSelectedVideo(trackUri) {
      try {
        const result = await withDatabase((db) =>
          awaitIdbRequest(db.transaction(STORE_NAME, "readonly").objectStore(STORE_NAME).get(trackUri)));
        if (result) logDebug(`[ivLyrics] Loaded selected video for ${trackUri}:`, result.youtubeVideoId);
        return result || null;
      } catch (error) {
        console.error("[ivLyrics] Failed to load selected video:", error);
        return null;
      }
    },

    async removeSelectedVideo(trackUri) {
      try {
        await withDatabase(db => runIdbTransaction(db, STORE_NAME, "readwrite", tx => {
          tx.objectStore(STORE_NAME).delete(trackUri);
        }, "Video selection transaction failed"));
        logDebug(`[ivLyrics] Removed selected video for ${trackUri}`);
        return true;
      } catch (error) {
        console.error("[ivLyrics] Failed to remove selected video:", error);
        return false;
      }
    },
  };
}

export const selectedVideoStore = createSelectedVideoStore({
  getIndexedDb: () => globalThis.indexedDB,
  waitForDatabaseRecovery: () => readSettingsDatabaseRecovery(globalThis),
  logDebug: createRuntimeDebugLogger(globalThis),
});
