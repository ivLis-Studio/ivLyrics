import { mapVideoTimeWithSkipSegments } from "./communityVideoTimeline.mjs";

const isAutoMatchedVideoInfo = (videoInfo) => {
    // A local edit explicitly makes zero a real first-lyric anchor, even if
    // the original automatic recommendation retained its system submitter.
    return videoInfo?.isAutoGenerated === true ||
        (videoInfo?.isAutoGenerated !== false && videoInfo?.submitterId === "system");
};

export const getLyricsStartTimeSeconds = (firstLyricTime) => {
    if (firstLyricTime === null || firstLyricTime === undefined) {
        return null;
    }

    const parsedFirstLyricTime = Number(firstLyricTime);
    return Number.isFinite(parsedFirstLyricTime)
        ? parsedFirstLyricTime / 1000
        : null;
};

export const getVideoSyncOffsetSeconds = (captionStartTime, lyricsStartTime, videoInfo) => {
    if (captionStartTime === null || captionStartTime === undefined) {
        return 0;
    }

    const parsedCaptionStartTime = Number(captionStartTime);
    if (!Number.isFinite(parsedCaptionStartTime)) {
        return 0;
    }

    if (lyricsStartTime === null || lyricsStartTime === undefined) {
        return 0;
    }

    const parsedLyricsStartTime = Number(lyricsStartTime);
    if (!Number.isFinite(parsedLyricsStartTime)) {
        return 0;
    }

    // System matches often use 0 as an unknown caption start. Treat that as song-start sync.
    if (isAutoMatchedVideoInfo(videoInfo) && Math.abs(parsedCaptionStartTime) < 0.001) {
        return 0;
    }

    return parsedCaptionStartTime - parsedLyricsStartTime;
};

export const resolveVideoSyncState = ({
    spotifyTime,
    lyricsStartTime,
    videoInfo,
    additionalDelaySeconds = 0,
    mapVideoTime,
}) => {
    const parsedSpotifyTime = Number(spotifyTime);
    const safeSpotifyTime = Number.isFinite(parsedSpotifyTime) ? parsedSpotifyTime : 0;
    const parsedAdditionalDelay = Number(additionalDelaySeconds);
    const safeAdditionalDelay = Number.isFinite(parsedAdditionalDelay) ? parsedAdditionalDelay : 0;
    const captionStartTime = videoInfo?.captionStartTime;
    const offset = getVideoSyncOffsetSeconds(captionStartTime, lyricsStartTime, videoInfo);
    const baseVideoTime = safeSpotifyTime + offset + safeAdditionalDelay;

    // The video has no timeline before 0. Keep its first frame still until the
    // Spotify position reaches the point that maps to the beginning of the video.
    if (baseVideoTime < 0) {
        return {
            baseVideoTime,
            targetVideoTime: 0,
            shouldHoldAtStart: true,
        };
    }

    const mappedVideoTime = typeof mapVideoTime === "function"
        ? Number(mapVideoTime(baseVideoTime, videoInfo?.skipSegments, captionStartTime))
        : baseVideoTime;

    return {
        baseVideoTime,
        targetVideoTime: Number.isFinite(mappedVideoTime) ? Math.max(0, mappedVideoTime) : 0,
        shouldHoldAtStart: false,
    };
};

export function createVideoBackgroundSync({ readVisualSettings, readGlobalSyncOffset, readActiveVideo }) {
    const getLiveVideoSyncInfo = (videoInfo, trackUri) => {
        const active = readActiveVideo();
        return trackUri && active?.trackUri === trackUri && active.youtubeVideoId === videoInfo?.youtubeVideoId
            ? active : videoInfo;
    };

    const computeVideoSyncState = ({ firstLyricTime, videoInfo, trackOffsetMs, trackUri = null, spotifyProgressMs }) => {
        const spotifyTime = spotifyProgressMs / 1000;
        const lyricsStartTime = getLyricsStartTimeSeconds(firstLyricTime);
        const visual = readVisualSettings();
        const globalDelayMs = visual ? Number(visual.delay || 0) : 0;
        const globalSyncOffsetMs = Number(readGlobalSyncOffset() ?? visual?.["global-sync-offset"] ?? 0) || 0;
        const additionalDelaySeconds = (trackOffsetMs + globalDelayMs + globalSyncOffsetMs) / 1000;
        return resolveVideoSyncState({
            spotifyTime,
            lyricsStartTime,
            videoInfo: getLiveVideoSyncInfo(videoInfo, trackUri),
            additionalDelaySeconds,
            mapVideoTime: mapVideoTimeWithSkipSegments,
        });
    };

    return { getLiveVideoSyncInfo, computeVideoSyncState };
}
