import { normalizeVideoSkipSegments } from "./communityVideoTimeline.mjs";

export const suppressedCommunityVideo = () => ({
  suppressVideoBackground: true,
  reason: "no-visible-community-video",
});

export async function readSavedVideoSelection({
  store, trackUri, signal, isCurrent, shouldHideDisliked, resolveHiddenCommunityVideo, reportError,
}) {
  if (!isCurrent()) return null;
  const saved = await store.getSelectedVideo(trackUri);
  if (!isCurrent() || !saved?.youtubeVideoId) return null;

  let selected = saved;
  if (saved.communityEntryId && shouldHideDisliked() && resolveHiddenCommunityVideo) {
    const resolution = await resolveHiddenCommunityVideo(trackUri, saved, true, { signal });
    if (!isCurrent()) return null;
    if (resolution?.hidden && shouldHideDisliked()) {
      const replacement = resolution.replacement?.youtubeVideoId ? resolution.replacement : null;
      let updated = false;
      try {
        updated = await store.replaceHiddenSelectedVideo(
          trackUri, saved, replacement, () => isCurrent() && shouldHideDisliked(),
        );
      } catch (error) {
        if (isCurrent()) reportError?.("[ivLyrics] Could not replace the hidden video:", error);
      }
      if (!isCurrent()) return null;
      if (updated) selected = replacement;
      else if (shouldHideDisliked()) return suppressedCommunityVideo();
    }
  }

  return selected ? {
    youtubeVideoId: selected.youtubeVideoId,
    youtubeTitle: selected.youtubeTitle,
    captionStartTime: selected.captionStartTime,
    skipSegments: normalizeVideoSkipSegments(selected.skipSegments),
    communityEntryId: selected.communityEntryId,
    isAutoGenerated: selected.isAutoGenerated,
  } : suppressedCommunityVideo();
}
