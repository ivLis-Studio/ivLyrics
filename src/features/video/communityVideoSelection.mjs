import { normalizeVideoSkipSegments as normalizeSelectorVideoSkipSegments } from "./communityVideoTimeline.mjs";

const COMMUNITY_VIDEO_MAX_START_TIME_SECONDS = 3600;
const COMMUNITY_VIDEO_MAX_SKIP_SEGMENTS = 10;
const normalizeCommunityVideoStartTime = (value) => {
  const parsed = Number.parseFloat(String(value ?? "").trim().replace(",", "."));
  if (!Number.isFinite(parsed)) return 0;
  const clamped = Math.max(0, Math.min(COMMUNITY_VIDEO_MAX_START_TIME_SECONDS, parsed));
  return Math.round(clamped * 10) / 10;
};
const getCommunityVideoWatchUrl = (videoId, startTime = 0) => {
  const normalizedVideoId = String(videoId || "").trim();
  if (!normalizedVideoId) return "";
  const url = new URL("https://www.youtube.com/watch");
  url.searchParams.set("v", normalizedVideoId);
  const normalizedStartTime = normalizeCommunityVideoStartTime(startTime);
  if (normalizedStartTime > 0) {
    url.searchParams.set("t", `${Math.floor(normalizedStartTime)}s`);
  }
  return url.toString();
};
const getCommunityVideoSelectionInfo = (
  video,
  startTime = video?.startTime,
  skipSegments = video?.skipSegments
) => ({
  youtubeVideoId: video?.youtubeVideoId,
  youtubeTitle: video?.youtubeTitle,
  captionStartTime: normalizeCommunityVideoStartTime(startTime),
  skipSegments: normalizeSelectorVideoSkipSegments(skipSegments, COMMUNITY_VIDEO_MAX_SKIP_SEGMENTS),
  communityEntryId: video?.isLocalOnly ? null : video?.id,
  isAutoGenerated:
    !video?.isLocalOnly &&
    (video?.submitterId === "system" || video?.isAutoGenerated === true),
  isLocalOnly: video?.isLocalOnly === true,
});

export function createCommunityVideoSelectionRequest(initialVideoId) {
  let activeVideoId = initialVideoId;
  let pending = null;

  async function select({ videoInfo, action, isCurrent, onError }) {
    if (!isCurrent()) return false;
    const request = {};
    pending = request;
    let result;
    let failure;
    try {
      result = await action();
    } catch (error) {
      failure = error;
      result = false;
    }
    if (pending !== request) return false;
    pending = null;
    if (!isCurrent() || result === null) return false;
    if (result === false) {
      onError(failure);
      return false;
    }
    activeVideoId = videoInfo?.youtubeVideoId ?? null;
    return true;
  }

  return {
    select,
    setActiveVideo: videoId => { activeVideoId = videoId; },
    canReplaceHiddenVideo: videoId => !pending && Boolean(videoId) && activeVideoId === videoId,
  };
}

export {
  COMMUNITY_VIDEO_MAX_START_TIME_SECONDS,
  COMMUNITY_VIDEO_MAX_SKIP_SEGMENTS,
  normalizeCommunityVideoStartTime,
  getCommunityVideoWatchUrl,
  getCommunityVideoSelectionInfo,
};

// 시간 포맷팅 (초 -> MM:SS.s)
export function formatCommunityVideoTime(seconds) {
  const mins = Math.floor(seconds / 60);
  const secs = seconds % 60;
  // 소수점 첫째 자리까지 표시
  const secsFormatted = secs.toFixed(1).padStart(4, "0");
  return `${mins}:${secsFormatted}`;
}
