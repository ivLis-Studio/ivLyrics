import { normalizeVideoSkipSegments } from "./communityVideoTimeline.mjs";

export function buildLocalCommunityVideoList(savedVideo, submitterId) {
  if (!savedVideo?.youtubeVideoId) return [];
  return [{
    id: "local",
    youtubeVideoId: savedVideo.youtubeVideoId,
    youtubeTitle: savedVideo.youtubeTitle,
    startTime: savedVideo.captionStartTime ?? 0,
    skipSegments: normalizeVideoSkipSegments(savedVideo.skipSegments),
    submitterId,
    isLocalOnly: true,
    isAutoGenerated: false,
    likes: 0,
    dislikes: 0,
    score: 0,
    userVote: null,
  }];
}

export function normalizeCommunityVideoList(response) {
  return Array.isArray(response?.videos) ? response.videos.map(video => ({
    ...video, skipSegments: normalizeVideoSkipSegments(video?.skipSegments),
  })) : [];
}

export function createCommunityVideoList({ onList, onLoading, onError }) {
  let videos = [];
  let pending = null;

  function publish(next) {
    videos = next;
    onList(videos);
    return videos;
  }

  function update(change) {
    // A reload can have sampled the list before a concurrent vote or delete.
    // Replay completed changes against that response before publishing it.
    pending?.changes.push(change);
    return publish(change(videos));
  }

  function cancel() {
    const previous = pending;
    pending = null;
    previous?.controller.abort();
  }

  async function load({ readVideos, signal, isCurrent }) {
    if (!isCurrent() || signal?.aborted) return;
    cancel();
    const controller = new AbortController();
    const request = { controller, changes: [] };
    pending = request;
    const lookupSignal = signal ? AbortSignal.any([signal, controller.signal]) : controller.signal;
    const ownsList = () => pending === request && !lookupSignal.aborted && isCurrent();
    onLoading(true);
    onError(false);

    try {
      const result = await readVideos(lookupSignal);
      if (ownsList()) publish(request.changes.reduce((list, change) => change(list), result));
    } catch {
      if (ownsList()) onError(true);
    } finally {
      if (ownsList()) {
        pending = null;
        onLoading(false);
      }
    }
  }

  return { load, update, cancel, getVideos: () => videos };
}
