import { getCommunityVideoSelectionInfo } from "./communityVideoSelection.mjs";
import { VideoMatch } from "./VideoMatch.js";

export function createVideoMatchSession({ normalizeIsrc }) {
    // Videos rejected for a track during this session (found to be another song
    // once their length was known), so a reload picks a different candidate.
    const videoMatchRejections = new Map();
    const VIDEO_MATCH_REJECTION_LIMIT = 200;
    const getRejectedVideoIds = (trackUri) => videoMatchRejections.get(trackUri) || null;
    const isRejectedVideoForTrack = (trackUri, videoId) => getRejectedVideoIds(trackUri)?.has(videoId) ?? false;
    const rejectVideoForTrack = (trackUri, videoId) => {
        if (!trackUri || !videoId) return;
        const rejected = videoMatchRejections.get(trackUri) || new Set();
        rejected.add(videoId);
        videoMatchRejections.delete(trackUri);
        videoMatchRejections.set(trackUri, rejected);
        if (videoMatchRejections.size > VIDEO_MATCH_REJECTION_LIMIT) {
            videoMatchRejections.delete(videoMatchRejections.keys().next().value);
        }
    };

    const describeVideoForMatch = (videoInfo, durationSeconds = 0) => ({
        title: videoInfo?.youtubeTitle || "",
        isrc: normalizeIsrc(videoInfo?.isrc) || "",
        // Entries without a community id were found by the server's own search.
        isAutoGenerated: videoInfo?.isAutoGenerated === true
            || videoInfo?.submitterId === "system"
            || videoInfo?.communityEntryId == null,
        communityEntryId: videoInfo?.communityEntryId ?? null,
        durationSeconds,
    });

    const pickVideoForTrack = (trackFacts, candidates, trackUri) => VideoMatch.pickCandidate(trackFacts, candidates, {
        describe: describeVideoForMatch,
        rejectedIds: getRejectedVideoIds(trackUri),
    });

    return { isRejectedVideoForTrack, rejectVideoForTrack, describeVideoForMatch, pickVideoForTrack };
}

// Server pick first, then the community alternatives it returned.
export const getYouTubeVideoCandidates = (responseData, communityVideos) => {
    const alternatives = (Array.isArray(communityVideos) ? communityVideos : [])
        .filter((video) => video?.youtubeVideoId)
        .map((video) => ({ ...getCommunityVideoSelectionInfo(video), isrc: video.isrc }));
    return responseData?.youtubeVideoId ? [responseData, ...alternatives] : alternatives;
};

