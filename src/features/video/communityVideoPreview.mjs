import { writeRuntimeDebug } from "#ivlyrics/spicetify/runtimeDebug.mjs";
import { mapVideoTimeWithSkipSegments as mapSelectorVideoTime, getVideoSkipSegmentAtTime as getSelectorVideoSkipSegment } from "./communityVideoTimeline.mjs";
import { readFirstLyricTime as readSelectorFirstLyricTime } from "./videoSyncRuntimeState.mjs";
import { watchYouTubeIframeApi } from "./youTubeIframeApi.mjs";

const EMPTY_SKIP_SEGMENTS = Object.freeze([]);

export function startPreviewHelperVideoDownload({
  videoId, videoHelper, toast, translate, onReady, onUnavailable, onError,
  now = Date.now, schedule = setTimeout, cancel = clearTimeout,
}) {
  let active = true;
  let abortDownload;
  let showingProgress = false;
  const startedAt = now();
  const showProgress = (key, percent, values) => {
    showingProgress = true;
    toast.progress(translate(key, values), percent);
  };
  const preparing = schedule(() => {
    if (active) showProgress("videoBackground.preparing", 0);
  }, 1500);
  const finish = () => {
    if (!active) return false;
    active = false;
    cancel(preparing);
    if (showingProgress) toast.dismissProgress();
    return true;
  };
  const fail = (message) => {
    if (!finish()) return;
    onError?.(message);
    toast.error(translate("videoBackground.helperError"));
  };

  async function request() {
    try {
      const available = await videoHelper?.isHelperAvailable();
      if (!active) return;
      if (!available) {
        finish();
        onUnavailable?.();
        toast.error(translate("videoBackground.helperNotConnected"));
        return;
      }

      abortDownload = videoHelper.requestVideo(videoId, {
        onProgress(progress) {
          if (!active) return;
          cancel(preparing);
          if (progress.status === "downloading") {
            const percent = Math.round(progress.percent || 0);
            showProgress("videoBackground.downloading", percent, { percent });
          } else if (progress.status === "checking") {
            showProgress("videoBackground.checking", 0);
          }
        },
        onComplete(url) {
          if (!finish()) return;
          onReady(url);
          if (now() - startedAt > 1500) toast.success(translate("videoBackground.downloadComplete"));
        },
        onError: fail,
      });
    } catch (error) {
      fail(error);
    }
  }

  void request();
  return () => {
    if (finish()) abortDownload?.();
  };
}

export function createCommunityVideoPreviews({
  host: window, document = window.document ?? globalThis.document, react, config: CONFIG,
  i18n: I18n, spicetify: Spicetify, toast: Toast, videoHelper: VideoHelperService,
}) {
  // 현재 음악 재생 시간에 맞춰 동기화된 YouTube 미리보기 컴포넌트
  // startTime: 영상에서 첫 가사가 시작되는 시간 (초)
  // VideoBackground와 동일한 로직: offset = captionStartTime - lyricsStartTime
  // 헬퍼 모드 지원: CONFIG.visual["video-helper-enabled"]가 true면 로컬 비디오 사용
  const getPreviewVideoSyncOffsetSeconds = (captionStartTime, lyricsStartTime, isAutoGenerated) => {
    if (captionStartTime === null || captionStartTime === undefined) {
      return 0;
    }

    const parsedCaptionStartTime = Number(captionStartTime);
    if (!Number.isFinite(parsedCaptionStartTime)) {
      return 0;
    }

    if (lyricsStartTime === null || lyricsStartTime === undefined) {
      return 0;
    }

    const parsedLyricsStartTime = Number(lyricsStartTime);
    if (!Number.isFinite(parsedLyricsStartTime)) {
      return 0;
    }

    // System matches often use 0 as an unknown caption start. Treat that as song-start sync.
    if (isAutoGenerated === true && Math.abs(parsedCaptionStartTime) < 0.001) {
      return 0;
    }

    return parsedCaptionStartTime - parsedLyricsStartTime;
  };

  const getPreviewLyricsStartTimeSeconds = () => {
    const firstLyricTime = readSelectorFirstLyricTime(window);
    if (firstLyricTime === null || firstLyricTime === undefined) {
      return null;
    }

    const parsedFirstLyricTime = Number(firstLyricTime);
    return Number.isFinite(parsedFirstLyricTime)
      ? parsedFirstLyricTime / 1000
      : null;
  };

  function usePreviewMedia(videoId, logTag) {
    const { useEffect, useLayoutEffect, useMemo, useState } = react;
    const [useHelper, setUseHelper] = useState(() => [true, "true"].includes(CONFIG?.visual?.["video-helper-enabled"]));
    const source = useMemo(() => ({ videoId, useHelper }), [videoId, useHelper]);
    const [download, setDownload] = useState(null);

    useEffect(() => {
      const handleHelperChange = (event) => setUseHelper(event.detail?.enabled === true);
      window.addEventListener("ivLyrics:videoHelperChanged", handleHelperChange);
      return () => window.removeEventListener("ivLyrics:videoHelperChanged", handleHelperChange);
    }, []);

    useLayoutEffect(() => {
      if (!useHelper || !videoId) return;
      return startPreviewHelperVideoDownload({
        videoId, videoHelper: VideoHelperService, toast: Toast,
        translate: (...args) => I18n.t(...args), onReady: url => setDownload({ source, url }),
        onUnavailable: logTag ? () => console.warn(`[${logTag}] Helper not available`) : undefined,
        onError: logTag ? error => console.error(`[${logTag}] Helper error:`, error) : undefined,
      });
    }, [source, logTag]);

    return { useHelper, source, helperVideoUrl: download?.source === source ? download.url : null };
  }

  const SyncedVideoPreview = ({ videoId, startTime, skipSegments = EMPTY_SKIP_SEGMENTS, isAutoGenerated = false }) => {
    const { useState, useEffect, useRef } = react;
    const containerRef = useRef(null);
    const playerRef = useRef(null);
    const videoRef = useRef(null); // HTML5 video for helper mode
    const { useHelper, source, helperVideoUrl } = usePreviewMedia(videoId, "SyncedVideoPreview");
    const [readySource, setReadySource] = useState(null);
    const [failedSource, setFailedSource] = useState(null);
    const isReady = readySource === source;
    const setIsReady = () => setReadySource(source);

    // 현재 Spotify 재생 위치를 skip 구간을 반영한 영상 시간으로 변환한다.
    const computePreviewVideoTime = () => {
      const spotifyPositionSec = Spicetify.Player.getProgress() / 1000;
      const lyricsStartTimeSec = getPreviewLyricsStartTimeSeconds();
      const captionStartTime = startTime;
      const offset = getPreviewVideoSyncOffsetSeconds(captionStartTime, lyricsStartTimeSec, isAutoGenerated);
      const baseVideoTime = Math.max(0, spotifyPositionSec + offset);
      return mapSelectorVideoTime(
        baseVideoTime,
        skipSegments,
        captionStartTime
      );
    };

    // 헬퍼 모드: video 요소 설정
    useEffect(() => {
      if (!useHelper || !helperVideoUrl || !videoRef.current) return;

      const video = videoRef.current;
      video.src = helperVideoUrl;
      video.muted = true;

      const handleCanPlay = () => {
        // 영상이 준비되면 즉시 현재 Spotify 위치로 동기화
        const videoTime = computePreviewVideoTime();

        if (videoTime >= 0 && video.duration > 0) {
          video.currentTime = Math.min(videoTime, video.duration);
        }

        setIsReady();
        if (Spicetify.Player.isPlaying()) {
          video.play().catch(() => { });
        }
      };

      video.addEventListener('canplay', handleCanPlay, { once: true });
      video.load();

      return () => {
        video.removeEventListener('canplay', handleCanPlay);
        video.pause();
        video.removeAttribute('src');
        video.load();
      };
    }, [useHelper, helperVideoUrl, startTime, skipSegments, isAutoGenerated]);

    // 헬퍼 모드: 동기화
    useEffect(() => {
      if (!useHelper || !videoRef.current || !isReady) return;

      const video = videoRef.current;

      const syncToSpotify = () => {
        const videoTime = computePreviewVideoTime();

        if (Math.abs(video.currentTime - videoTime) > 0.5) {
          video.currentTime = videoTime;
        }

        if (Spicetify.Player.isPlaying()) {
          if (video.paused) video.play().catch(() => { });
        } else if (!video.paused) {
          video.pause();
        }
      };

      const syncInterval = setInterval(syncToSpotify, 500);
      syncToSpotify();

      const handlePlayPause = () => syncToSpotify();
      Spicetify.Player.addEventListener("onplaypause", handlePlayPause);

      return () => {
        clearInterval(syncInterval);
        Spicetify.Player.removeEventListener("onplaypause", handlePlayPause);
      };
    }, [useHelper, isReady, startTime, skipSegments, isAutoGenerated]);

    // 일반 모드: YouTube IFrame
    useEffect(() => {
      if (useHelper) return;
      if (!videoId || !containerRef.current) return;

      let isMounted = true;
      let initialSyncTimer = null;
      setFailedSource(null);
      const handlePlayerError = (error) => {
        if (!isMounted) return;
        setFailedSource(source);
        console.error("[SyncedVideoPreview] Player error:", error);
      };

      // Spotify 재생 위치에 맞춰 동기화
      // VideoBackground와 동일한 로직 사용:
      // offset = captionStartTime - lyricsStartTime
      // targetVideoTime = spotifyTime + offset
      const syncToSpotify = () => {
        if (!playerRef.current) return;

        try {
          // player가 준비되었는지 확인
          if (typeof playerRef.current.seekTo !== "function") return;
          if (typeof playerRef.current.getPlayerState !== "function") return;

          const videoTime = computePreviewVideoTime();

          playerRef.current.seekTo(videoTime, true);

          // YT.PlayerState: -1 (unstarted), 0 (ended), 1 (playing), 2 (paused), 3 (buffering), 5 (cued)
          const playerState = playerRef.current.getPlayerState();

          if (Spicetify.Player.isPlaying()) {
            if (playerState !== 1 && playerState !== 3) {
              // not playing and not buffering
              playerRef.current.playVideo();
            }
          } else if (playerState === 1) {
            // playing
            playerRef.current.pauseVideo();
          }
        } catch (e) {
          console.error("[SyncedVideoPreview] Sync error:", e);
        }
      };

      // YouTube IFrame API 로드 확인
      const initPlayer = (api) => {
        if (!isMounted || !containerRef.current) return;

        // 고유 ID 생성
        const playerId = `preview-player-${videoId}-${Date.now()}`;
        const playerDiv = document.createElement("div");
        playerDiv.id = playerId;
        containerRef.current.innerHTML = "";
        containerRef.current.appendChild(playerDiv);

        playerRef.current = new api.Player(playerId, {
          videoId,
          width: "100%",
          height: 200,
          playerVars: {
            autoplay: 1,
            controls: 0,
            disablekb: 1,
            fs: 0,
            iv_load_policy: 3,
            modestbranding: 1,
            rel: 0,
            showinfo: 0,
            mute: 1,
            playsinline: 1,
            origin: window.location.origin,
          },
          events: {
            onReady: (event) => {
              if (!isMounted) return;
              writeRuntimeDebug(window, "[SyncedVideoPreview] Player ready");
              setFailedSource(null);
              setIsReady();

              // 초기 동기화
              clearTimeout(initialSyncTimer);
              initialSyncTimer = setTimeout(() => {
                if (isMounted) syncToSpotify();
              }, 500);
            },
            onStateChange: (event) => {
              if (!isMounted) return;
              // 버퍼링이 끝나고 재생 준비되면 동기화
              if (
                event.data === api.PlayerState?.PLAYING ||
                event.data === api.PlayerState?.CUED
              ) {
                syncToSpotify();
              }
            },
            onError: (event) => handlePlayerError(event.data),
          },
        });
      };

      const stopWaitingForApi = watchYouTubeIframeApi({
        host: window, document, onReady: initPlayer, onError: handlePlayerError,
      });

      // 주기적 동기화 (건너뛰기 경계도 빠르게 반영)
      const syncInterval = setInterval(() => {
        if (isMounted) syncToSpotify();
      }, 500);

      // Spotify 재생/일시정지 이벤트 리스너
      const handlePlayPause = () => {
        if (!isMounted) return;
        syncToSpotify();
      };

      Spicetify.Player.addEventListener("onplaypause", handlePlayPause);

      return () => {
        isMounted = false;
        stopWaitingForApi();
        clearTimeout(initialSyncTimer);
        clearInterval(syncInterval);
        Spicetify.Player.removeEventListener("onplaypause", handlePlayPause);
        if (playerRef.current) {
          try {
            playerRef.current.destroy();
          } catch (e) { }
          playerRef.current = null;
        }
      };
    }, [useHelper, videoId, startTime, skipSegments, isAutoGenerated]);

    return react.createElement(
      "div",
      {
        className: "community-video-embed synced-preview",
      },
      // 헬퍼 모드: video 태그
      useHelper && react.createElement("video", {
        ref: videoRef,
        style: { width: "100%", height: "200px", background: "#000", objectFit: "contain" },
        muted: true,
        playsInline: true,
      }),
      // 일반 모드: YouTube 컨테이너
      !useHelper && react.createElement("div", {
        ref: containerRef,
        style: { width: "100%", height: "200px", background: "#000" },
      }),
      (failedSource === source || !isReady) &&
      react.createElement(
        "div",
        {
          className: "preview-loading",
        },
        I18n.t(failedSource === source ? "videoBackground.error" : "communityVideo.loading")
      )
    );
  };

  // 시간 입력 시 iframe 리로드 방지를 위한 단순 미리보기 컴포넌트
  // 헬퍼 모드 지원
  const SimpleVideoPreview = ({ videoId, startTime, skipSegments = EMPTY_SKIP_SEGMENTS }) => {
    const { useEffect, useLayoutEffect, useRef } = react;
    const containerRef = useRef(null);
    const playerRef = useRef(null);
    const videoRef = useRef(null);
    const { useHelper, helperVideoUrl } = usePreviewMedia(videoId);
    const startTimeRef = useRef(startTime);
    useLayoutEffect(() => { startTimeRef.current = startTime; }, [startTime]);

    // 헬퍼 모드: video 시간 설정
    useEffect(() => {
      if (!useHelper || !videoRef.current || !helperVideoUrl) return;
      const video = videoRef.current;
      video.muted = true;
      video.currentTime = startTime;
      video.play().catch(() => { });
    }, [useHelper, helperVideoUrl, startTime]);

    // 헬퍼 미리보기에서 등록한 비음악 구간을 즉시 건너뜁니다.
    useEffect(() => {
      if (!useHelper || !videoRef.current || !helperVideoUrl) return;
      const video = videoRef.current;
      const handleTimeUpdate = () => {
        const segment = getSelectorVideoSkipSegment(video.currentTime, skipSegments, startTime);
        if (segment) video.currentTime = segment.end;
      };
      video.addEventListener("timeupdate", handleTimeUpdate);
      return () => video.removeEventListener("timeupdate", handleTimeUpdate);
    }, [useHelper, helperVideoUrl, startTime, skipSegments]);

    // 일반 모드: YouTube
    useEffect(() => {
      if (useHelper) return;
      if (!videoId || !containerRef.current) return;

      let isMounted = true;
      const initPlayer = (api) => {
        if (!isMounted || !containerRef.current) return;

        // 고유 ID 생성
        const playerId = `simple-preview-${videoId}-${Date.now()}`;
        const playerDiv = document.createElement("div");
        playerDiv.id = playerId;
        containerRef.current.innerHTML = "";
        containerRef.current.appendChild(playerDiv);

        playerRef.current = new api.Player(playerId, {
          videoId,
          width: "100%",
          height: "180",
          playerVars: {
            autoplay: 1,
            controls: 0,
            disablekb: 1,
            fs: 0,
            iv_load_policy: 3,
            modestbranding: 1,
            rel: 0,
            showinfo: 0,
            // Spotify is playing the song; a preview is only a picture.
            mute: 1,
            playsinline: 1,
            start: Math.floor(startTime),
            origin: window.location.origin,
          },
          events: {
            onReady: (event) => {
              if (isMounted && playerRef.current) {
                playerRef.current.seekTo(startTimeRef.current, true);
                playerRef.current.playVideo();
              }
            },
          },
        });
      };

      const stopWaitingForApi = watchYouTubeIframeApi({
        host: window, document, onReady: initPlayer,
        onError: (error) => console.warn("[SimpleVideoPreview] Could not initialize YouTube:", error),
      });

      return () => {
        isMounted = false;
        stopWaitingForApi();
        if (playerRef.current) {
          try {
            playerRef.current.destroy();
          } catch (e) { }
          playerRef.current = null;
        }
      };
    }, [useHelper, videoId]);

    useEffect(() => {
      if (useHelper) return;
      if (playerRef.current && typeof playerRef.current.seekTo === "function") {
        playerRef.current.seekTo(startTime, true);
        playerRef.current.playVideo();
      }
    }, [useHelper, startTime]);

    // YouTube 미리보기에서도 여러 비음악 구간을 순서대로 건너뜁니다.
    useEffect(() => {
      if (useHelper) return;
      const intervalId = setInterval(() => {
        if (
          !playerRef.current ||
          typeof playerRef.current.getCurrentTime !== "function" ||
          typeof playerRef.current.seekTo !== "function"
        ) return;
        const segment = getSelectorVideoSkipSegment(
          playerRef.current.getCurrentTime(),
          skipSegments,
          startTime
        );
        if (segment) playerRef.current.seekTo(segment.end, true);
      }, 250);
      return () => clearInterval(intervalId);
    }, [useHelper, startTime, skipSegments]);

    return react.createElement(
      "div",
      {
        className: "community-video-embed submit-preview",
        style: { position: "relative" },
      },
      // 헬퍼 모드: video 태그
      useHelper && react.createElement("video", {
        ref: videoRef,
        src: helperVideoUrl,
        style: { width: "100%", height: "180px", background: "#000", objectFit: "contain" },
        muted: true,
        playsInline: true,
        autoPlay: true,
      }),
      // 일반 모드: YouTube 컨테이너
      !useHelper && react.createElement("div", {
        ref: containerRef,
        style: { width: "100%", height: "180px", background: "#000" },
      }),
      react.createElement("div", {
        style: {
          position: "absolute",
          top: 0,
          left: 0,
          right: 0,
          bottom: 0,
          cursor: "default",
        },
      })
    );
  };

  return {
    SyncedVideoPreview, SimpleVideoPreview,
  };
}
